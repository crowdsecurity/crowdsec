func TestBuildChallengeAlertRejected(t *testing.T) {
	setupGeoIP(t)
	w := makeRuntime()

	alert := w.buildChallengeAlert(nil, challengeReq(t, true), rejectedInfo(t))

	require.Equal(t, types.BotDetectionAlertKind.String(), alert.Kind)
	require.NotNil(t, alert.Scenario)
	assert.Equal(t, challengeScenario, *alert.Scenario)

	// The alert must satisfy the swagger contract (all required fields set).
	require.NoError(t, alert.Validate(strfmt.Default))

	// Raw detection data lives in the event Meta (like the WAF path); the alert
	// context (Meta) is left to the operator's context file, not hardcoded.
	assert.Equal(t, string(ChallengeReasonRejected), metaValue(alert, "challenge_event"))
	assert.Equal(t, "105", metaValue(alert, "request_score"))
	assert.Equal(t, "cdp,webdriver", metaValue(alert, "request_score_reasons"))
	assert.Equal(t, "true", metaValue(alert, "fingerprint_bot"))
	assert.Contains(t, metaValue(alert, "bot_signals"), "cdp")
	assert.Equal(t, "FS_RUNTIME", metaValue(alert, "fsid"))
	assert.NotEmpty(t, metaValue(alert, "os"))
	assert.Equal(t, "US", alert.Source.Cn)
}

func TestBuildChallengeAlertFailed(t *testing.T) {
	setupGeoIP(t)
	w := makeRuntime()

	info := ChallengeEventInfo{
		Reason:     ChallengeReasonFailed,
		FailReason: "cookie expired",
	}
	alert := w.buildChallengeAlert(nil, challengeReq(t, true), info)

	require.NoError(t, alert.Validate(strfmt.Default))
	assert.Equal(t, challengeScenario, *alert.Scenario)
	assert.Equal(t, string(ChallengeReasonFailed), metaValue(alert, "challenge_event"))
	assert.Equal(t, "cookie expired", metaValue(alert, "challenge_fail_reason"))
	// No fingerprint on a failed submission → no bot signals.
	assert.Empty(t, metaValue(alert, "bot_signals"))
}

// TestBuildChallengeAlertContextFromConfig proves the alert context (Meta) is
// generated by the alert-context engine from a context config (mirroring the
// hub crowdsecurity/appsec-bot-detection file), reading the event Meta and the
// Unmarshaled fingerprint — not hardcoded in buildChallengeAlert.
func TestBuildChallengeAlertContextFromConfig(t *testing.T) {
	setupGeoIP(t)
	require.NoError(t, alertcontext.NewAlertContext(map[string][]string{
		"fingerprint_id":   {"evt.Meta.fsid"},
		"operating_system": {"evt.Meta.os"},
		"bot_detected":     {"evt.Meta.fingerprint_bot"},
		"challenge_event":  {"evt.Meta.challenge_event"},
		"detected_signals": {`evt.Unmarshaled.fingerprint != nil ? evt.Unmarshaled.fingerprint.BotSignals() : ""`},
		// A config expression consuming a hook var off the appsec event.
		"score_via_hookvar": {"evt.Appsec.HookVars.request_score"},
	}, alertcontext.MaxContextValueLen))

	w := makeRuntime()
	state := &AppsecRequestState{HookVars: map[string]string{"request_score": "105"}}
	alert := w.buildChallengeAlert(state, challengeReq(t, true), rejectedInfo(t))

	assert.Equal(t, []string{"FS_RUNTIME"}, contextValues(t, alert, "fingerprint_id"))
	assert.Equal(t, []string{"true"}, contextValues(t, alert, "bot_detected"))
	assert.Equal(t, []string{string(ChallengeReasonRejected)}, contextValues(t, alert, "challenge_event"))
	assert.NotEmpty(t, contextValues(t, alert, "operating_system"))
	assert.Contains(t, contextValues(t, alert, "detected_signals"), "cdp")
	// The hook var is reachable by config expr via evt.Appsec.HookVars.
	assert.Equal(t, []string{"105"}, contextValues(t, alert, "score_via_hookvar"))
}

func TestBuildChallengeOverflow(t *testing.T) {
	setupGeoIP(t)
	w := makeRuntime()

	state := &AppsecRequestState{
		Response: AppsecTempResponse{SendAlert: true},
		HookVars: map[string]string{"request_score": "105"},
	}
	evt := w.buildChallengeOverflow(state, challengeReq(t, true), rejectedInfo(t), state.HookVars)

	require.NotNil(t, evt)
	assert.Equal(t, pipeline.APPSEC, evt.Type)
	require.NotNil(t, evt.Overflow.Alert)
	assert.Equal(t, types.BotDetectionAlertKind.String(), evt.Overflow.Alert.Kind)
	require.Len(t, evt.Overflow.APIAlerts, 1)
	assert.Contains(t, evt.Overflow.Sources, testIPUS)
	// Hook vars are carried onto the overflow (like the WAF alert path).
	assert.Equal(t, "105", evt.Appsec.HookVars["request_score"])
}

func TestBuildChallengeOverflowCancelSuppresses(t *testing.T) {
	w := makeRuntime()

	state := &AppsecRequestState{Response: AppsecTempResponse{SendAlert: false}}
	evt := w.buildChallengeOverflow(state, challengeReq(t, true), rejectedInfo(t), nil)

	assert.Nil(t, evt, "CancelAlert (SendAlert=false) must suppress the alert")
}

